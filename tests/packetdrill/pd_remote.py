"""Private SSH wire-server supervisor; requests and replies are JSON lines.

The SSH channel stays open for the run. EOF, signals and a watchdog all trigger
cleanup. Both physical interfaces stay in their existing network namespaces.
"""
import base64
import contextlib
import json
import math
import os
from pathlib import Path
import re
import select
import shlex
import shutil
import signal
import socket
import subprocess
import sys
import tempfile
import time

import pd_common as pd

SUPERVISOR_SIGNALS = (signal.SIGHUP, signal.SIGINT, signal.SIGTERM, signal.SIGALRM)


class RemoteWireServer:
    def __init__(self, args, out):
        if not re.fullmatch(r'[A-Za-z0-9_@.:-]+', args.server_host) or args.server_host.startswith('-'):
            raise RuntimeError('Invalid SSH destination: ' + args.server_host)
        ssh = shlex.split(args.ssh_command)
        if not ssh:
            raise RuntimeError('--ssh-command must specify an executable')
        self.args, self.out = args, out
        self.buffer = b''
        self.stderr = (out / 'server-ssh.log').open('wb')
        remote_command = shlex.join(['python3', '-u', str(Path(args.server_dir) / 'pd_remote.py')])
        try:
            self.process = subprocess.Popen(ssh + ['--', args.server_host, remote_command],
                                            stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                            stderr=self.stderr, env=pd.clean_environment(),
                                            start_new_session=True)
        except BaseException:
            self.stderr.close()
            raise

    def request(self, action, **values):
        # Finish a protocol transaction before handling Ctrl-C, so its reply
        # cannot be confused with the response to the subsequent stop request.
        with pd.defer_interrupts():
            return self._request(action, **values)

    def _request(self, action, **values):
        try:
            self.process.stdin.write((json.dumps(dict(action=action, **values)) + '\n').encode())
            self.process.stdin.flush()
        except (BrokenPipeError, OSError) as error:
            raise RuntimeError('SSH wire-server channel failed; see server-ssh.log') from error
        end = time.monotonic() + 30
        while b'\n' not in self.buffer:
            remaining = end - time.monotonic()
            if remaining <= 0 or not select.select([self.process.stdout], [], [], max(remaining, 0))[0]:
                raise RuntimeError('SSH wire-server response timed out; see server-ssh.log')
            chunk = os.read(self.process.stdout.fileno(), 65536)
            if not chunk:
                raise RuntimeError('SSH wire-server channel closed; see server-ssh.log')
            self.buffer += chunk
        line, self.buffer = self.buffer.split(b'\n', 1)
        result = json.loads(line)
        if not result['ok']:
            raise RuntimeError('Remote wire server: ' + result['error'])
        return result.get('result')

    def setup(self):
        return self.request('setup', server_interface=self.args.server_interface,
                            server_ip=self.args.server_ip, client_ip=self.args.client_ip,
                            packetdrill=self.args.server_packetdrill,
                            cache_dir=self.args.server_cache_dir,
                            # Restore the remote host even if SSH is lost or the client is killed.
                            watchdog=math.ceil(self.args.timeout + 30) * self.args.test_count + 90)

    def start(self):
        return self.request('start')

    def finish(self, failed=False):
        return self.request('finish', failed=failed).encode()

    def stop(self, log=None):
        text = self.request('stop')
        if log is None:
            return
        data = text.encode()
        if log.closed:
            Path(log.name).write_bytes(data)
        else:
            log.write(data)
            log.flush()

    def close(self):
        error = None
        try:
            if self.process.poll() is None:
                result = self.request('close')
                for name, data in result.items():
                    # Names are generated by this helper, never remote absolute paths.
                    (self.out / ('server-' + Path(name).name)).write_bytes(base64.b64decode(data))
            else:
                raise RuntimeError('SSH ended before confirming remote cleanup; see server-ssh.log')
        except Exception as failure:
            error = failure
        finally:
            with contextlib.suppress(OSError):
                self.process.stdin.close()
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                pd.stop_process(self.process)
            self.process.stdout.close()
            self.stderr.close()
        if error:
            raise error
        if self.process.returncode:
            raise RuntimeError('Remote supervisor exited ' + str(self.process.returncode))


class WireSession:
    def __init__(self):
        self.out = Path(tempfile.mkdtemp(prefix='xlio-pd-remote-'))
        self.server = None
        self.interface = None
        self.rules = []

    def setup(self, request):
        if self.interface:
            raise RuntimeError('Wire server is already configured')
        if os.geteuid() != 0:
            raise RuntimeError('SSH user must be root for wire-server network setup')
        for tool in ('ip', 'ss', 'iptables', 'iptables-save'):
            if not shutil.which(tool):
                raise RuntimeError('Missing remote runtime dependency: ' + tool)
        # Read independently on the remote host; no shared filesystem is needed.
        self.binary = (Path(request['packetdrill']).resolve(strict=True)
                       if request['packetdrill'] else
                       pd.cache_binary(request['cache_dir'] or os.environ.get('PD_CACHE_DIR', pd.ROOT / '.cache')))
        if not self.binary.is_file() or not os.access(self.binary, os.X_OK):
            raise RuntimeError('Remote Packetdrill is missing; run pd prepare on the server')
        if not request['packetdrill']:
            pd.verify_cache(self.binary)
        interface = pd.interface(request['server_interface'])
        peer = pd.address(interface, request['server_ip'])
        if request['client_ip'] == request['server_ip']:
            raise RuntimeError('Use distinct client and server addresses')
        if interface['mtu'] != 1500 or 'UP' not in interface['flags']:
            raise RuntimeError('Remote wire interface must be up with MTU 1500')
        client_ip = str(pd.ipaddress.IPv4Address(request['client_ip']))
        if pd.ipaddress.IPv4Address(client_ip) not in peer.network:
            raise RuntimeError('Client IP must be in the remote interface subnet')
        # These are the rules inserted by the pinned Packetdrill wire server:
        # TCP/UDP bind/connect port 8080 and its default PSP UDP port 0.
        rules = [['-s', client_ip, '-p', protocol, '-m', protocol, port_flag, port, '-j', 'DROP']
                 for protocol, port_flag, port in [('tcp', '--dport', '8080'), ('tcp', '--sport', '8080'),
                                                  ('udp', '--dport', '8080'), ('udp', '--sport', '8080'),
                                                  ('udp', '--dport', '0')]]
        for rule in rules:
            result = pd.command('iptables', '-w', '5', '-C', 'INPUT', *rule, check=False)
            if result.returncode != 1:
                raise RuntimeError('Cannot own Packetdrill firewall rules: rule already exists or iptables failed')
        self.rules = rules
        (self.out / 'iptables-before.save').write_bytes(pd.command('iptables-save').stdout)
        signal.alarm(int(request['watchdog']))
        self.interface = request['server_interface']
        return dict(interface=interface, hostname=socket.gethostname(),
                    packetdrill=str(self.binary), packetdrill_sha256=pd.digest(self.binary),
                    packetdrill_origin='explicit; revision unverified' if request['packetdrill'] else 'verified prepared cache',
                    recovery_directory=str(self.out))

    def start(self):
        if not self.interface:
            raise RuntimeError('Wire server is not ready to start')
        # The supervisor also handles HUP/ALRM, so protect all of its ownership
        # signals while the shared listener is acquired and registered.
        with pd.defer_interrupts(SUPERVISOR_SIGNALS):
            if self.server is None:
                self.server = pd.WireServer(self.binary, self.interface, self.out / 'wire.log')
            return self.server.start()

    def finish(self, failed=False):
        if self.server is None:
            raise RuntimeError('No wire server owns the current case')
        text = self.server.finish(failed=failed).decode(errors='replace')
        if failed:
            # A killed worker may leave rules behind. Remove them before the
            # next listener starts, keeping failure isolation explicit.
            self.stop()
        return text

    def stop(self):
        with pd.defer_interrupts(SUPERVISOR_SIGNALS):
            return self._stop()

    def _stop(self):
        if self.server:
            self.server.stop()
            self.server = None
        for rule in self.rules:
            while True:
                result = pd.command('iptables', '-w', '5', '-C', 'INPUT', *rule, check=False)
                if result.returncode == 1:
                    break
                if result.returncode:
                    raise RuntimeError('Could not check Packetdrill firewall cleanup')
                pd.command('iptables', '-w', '5', '-D', 'INPUT', *rule)
        path = self.out / 'wire.log'
        return path.read_text(errors='replace') if path.exists() else ''

    def close(self):
        # No NIC, address, namespace or VF configuration is changed remotely.
        try:
            self.stop()
            (self.out / 'iptables-after.save').write_bytes(pd.command('iptables-save').stdout)
        except Exception as error:
            raise RuntimeError('{}; recovery state retained at {}'.format(error, self.out)) from error
        snapshots = {p.name: base64.b64encode(p.read_bytes()).decode()
                     for p in self.out.iterdir() if p.is_file()}
        shutil.rmtree(self.out)
        return snapshots


def serve():
    def interrupted(number, frame):
        raise pd.Interrupted(number)

    for number in SUPERVISOR_SIGNALS:
        signal.signal(number, interrupted)
    session = WireSession()
    closed = False
    cleanup_attempted = False
    try:
        netns = os.stat('/proc/self/ns/net').st_ino
        with pd.lock('/run/lock/xlio-pd-' + str(netns) + '.lock'):
            try:
                for line in sys.stdin:
                    try:
                        request = json.loads(line)
                        action = request['action']
                        if action == 'setup':
                            result = session.setup(request)
                        elif action == 'start':
                            result = session.start()
                        elif action == 'finish':
                            result = session.finish(request.get('failed', False))
                        elif action == 'stop':
                            result = session.stop()
                        elif action == 'close':
                            signal.alarm(0)
                            for number in SUPERVISOR_SIGNALS:
                                signal.signal(number, signal.SIG_IGN)
                            cleanup_attempted = True
                            result = session.close()
                            closed = True
                        else:
                            raise RuntimeError('Unknown wire-server action: ' + str(action))
                        print(json.dumps(dict(ok=True, result=result)), flush=True)
                        if closed:
                            return
                    except pd.Interrupted:
                        raise
                    except Exception as error:
                        print(json.dumps(dict(ok=False, error=str(error))), flush=True)
            finally:
                if not closed and not cleanup_attempted:
                    for number in SUPERVISOR_SIGNALS:
                        signal.signal(number, signal.SIG_IGN)
                    session.close()
                    closed = True
    finally:
        if not closed:
            # A lock failure happened before the session could mutate anything.
            if not session.interface:
                shutil.rmtree(session.out, ignore_errors=True)


if __name__ == '__main__':
    serve()
